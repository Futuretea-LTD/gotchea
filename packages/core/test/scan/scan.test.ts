import { mkdir, mkdtemp, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { defaultConfig } from '../../src/config/load.js';
import type { Progress } from '../../src/model/progress.js';
import type { QuestionPrivate } from '../../src/model/question.js';
import { scanRepo, type ScanOptions } from '../../src/scan/scan.js';
import { FsProgressStore } from '../../src/store/progress-store.js';
import { FsQuestionStore } from '../../src/store/question-store.js';
import { repoPaths } from '../../src/store/paths.js';

let root: string;
let home: string;
const env = () => ({ GOTCHEA_HOME: home });
const scan = (over: Partial<ScanOptions> = {}) => scanRepo({ root, repoId: 'test-repo', useGit: false, env: env(), ...over });

async function put(path: string, text: string) {
  await mkdir(dirname(join(root, path)), { recursive: true });
  await writeFile(join(root, path), text);
}

/** A function of `n` distinct statements. */
const fn = (name: string, n: number, tweak = -1) =>
  `export function ${name}(a: number): number {\n${Array.from({ length: n }, (_, i) => `  a = a + ${i === tweak ? 1000 + i : i};`).join('\n')}\n  return a;\n}\n`;

const question = (id: string, chunkId: string, chunkHash: string): QuestionPrivate => ({
  id,
  chunkId,
  chunkHash,
  type: 'behavior',
  stem: 'What does it return?',
  options: ['a', 'b', 'c', 'd'],
  correctIndex: 1,
  explanation: 'because',
  refs: [],
  difficulty: 2,
  lang: 'en',
  generatedBy: 'test',
  status: 'ok',
  flagged: false,
  chunkLines: 0,
  promptVersion: 'p1',
  verifiedBy: null,
  createdAt: '2026-10-14T00:00:00.000Z',
});

const passed = (hash: string): Progress => ({
  stability: 10,
  lastReviewedAt: '2026-10-10T00:00:00.000Z',
  lastPassedHash: hash,
  lastSeenHash: hash,
  mustRepass: false,
  history: [],
});

beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), 'gotchea-scan-'));
  home = await mkdtemp(join(tmpdir(), 'gotchea-home-'));
  await put('src/big.ts', `${fn('alpha', 120)}\n${fn('beta', 100)}\n`);
  await put('src/small.ts', `import { alpha } from './big';\nexport const run = () => alpha(1);\n`);
  await put('pkg/mod.py', 'def helper(x):\n    return x + 1\n');
  await put('main.py', 'from pkg.mod import helper\nprint(helper(1))\n');
  await put('node_modules/dep/index.js', 'module.exports = 1;\n');
  await put('dist/out.js', 'x();\n');
  await put('src/small.test.ts', 'test();\n');
  await put('pnpm-lock.yaml', 'lockfileVersion: 9\n');
  await put('src/gen.ts', '// @generated by a tool\nexport const x = 1;\n');
  await put('.gitignore', 'ignored/\n');
  await put('ignored/a.ts', 'export const y = 1;\n');
});

afterEach(async () => {
  await rm(root, { recursive: true, force: true, maxRetries: 5 });
  await rm(home, { recursive: true, force: true, maxRetries: 5 });
});

describe('scanRepo', () => {
  it('chunks the repo, computes fanIn and writes a deterministic chunks.json', async () => {
    const r = await scan();
    expect(r.files).toEqual(['main.py', 'pkg/mod.py', 'src/big.ts', 'src/small.ts']);
    expect(r.diff.added.length).toBe(r.chunks.length);
    const byId = new Map(r.chunks.map((c) => [c.id, c]));
    expect([...byId.keys()]).toEqual(['.', 'main.py', 'pkg', 'pkg/mod.py', 'src', 'src/big.ts', 'src/big.ts#alpha', 'src/big.ts#beta', 'src/small.ts']);
    expect(byId.get('src/big.ts#alpha')!.metrics.fanIn).toBe(1);
    expect(byId.get('src/big.ts#beta')!.metrics.fanIn).toBe(0);
    expect(byId.get('src/big.ts')!.metrics.fanIn).toBe(1);
    expect(byId.get('pkg/mod.py')!.metrics.fanIn).toBe(1);
    expect(byId.get('pkg')!.metrics.fanIn).toBe(1);

    const first = await readFile(repoPaths(root).chunks, 'utf8');
    const second = await scan();
    expect(await readFile(repoPaths(root).chunks, 'utf8')).toBe(first);
    expect(second.diff.unchanged.length).toBe(r.chunks.length);
    expect(first.endsWith('\n')).toBe(true);
    expect(JSON.parse(first)).toMatchObject({ version: 1, normalization: 'n1' });
  });

  it('includes test files only when opted in', async () => {
    const r = await scan({ config: { ...defaultConfig(), includeTests: true } });
    expect(r.files).toContain('src/small.test.ts');
  });

  it('ignores comment-only edits and decays + stales on real edits', async () => {
    const r1 = await scan();
    const alpha = r1.chunks.find((c) => c.id === 'src/big.ts#alpha')!;
    const questions = new FsQuestionStore(root);
    const progress = new FsProgressStore('test-repo', env());
    await questions.save(alpha.id, [question('q1', alpha.id, alpha.contentHash)]);
    await progress.save({ version: 1, repoId: 'test-repo', chunks: { [alpha.id]: passed(alpha.contentHash) } });

    await put('src/big.ts', `// header comment\n${fn('alpha', 120).replace('{\n', '{ // why\n')}\n\n\n${fn('beta', 100)}\n`);
    const r2 = await scan();
    expect(r2.diff.changed).toEqual([]);
    expect(r2.staleQuestions).toBe(0);
    expect(r2.decayed).toEqual([]);

    // Change 12 of 123 normalized lines.
    let edited = fn('alpha', 120);
    for (let i = 0; i < 12; i++) edited = edited.replace(`a = a + ${i * 10};`, `a = a - ${i * 10};`);
    await put('src/big.ts', `${edited}\n${fn('beta', 100)}\n`);
    const r3 = await scan();
    const change = r3.diff.changed.find((c) => c.id === alpha.id)!;
    expect(change.changeRatio).toBeCloseTo(12 / 123, 6);
    expect(r3.staleQuestions).toBe(1);
    expect(r3.decayed).toEqual([{ id: alpha.id, fromHash: alpha.contentHash, toHash: change.newHash, changeRatio: change.changeRatio }]);
    expect(r3.reconciled).toEqual([]);
    expect((await questions.list(alpha.id))[0]!.status).toBe('stale');
    const p = (await progress.load()).chunks[alpha.id]!;
    expect(p.stability).toBeCloseTo(10 * (1 - 12 / 123), 6);
    expect(p.lastSeenHash).toBe(change.newHash);
    expect(p.mustRepass).toBe(false);
  });

  it('moves questions and progress with a renamed file and deletes pools of removed chunks', async () => {
    const r1 = await scan();
    const small = r1.chunks.find((c) => c.id === 'src/small.ts')!;
    const beta = r1.chunks.find((c) => c.id === 'src/big.ts#beta')!;
    const questions = new FsQuestionStore(root);
    await questions.save(small.id, [question('q1', small.id, small.contentHash)]);
    await questions.save(beta.id, [question('q2', beta.id, beta.contentHash)]);
    await new FsProgressStore('test-repo', env()).save({ version: 1, repoId: 'test-repo', chunks: { [small.id]: passed(small.contentHash) } });

    await rename(join(root, 'src/small.ts'), join(root, 'src/runner.ts'));
    await put('src/big.ts', `${fn('alpha', 120)}\n${fn('gamma', 100, 3)}\n`);
    const r2 = await scan();
    expect(r2.diff.moved).toContainEqual({ from: 'src/small.ts', to: 'src/runner.ts', kind: 'file', contentHash: small.contentHash });
    expect(r2.diff.removed).toContain('src/big.ts#beta');
    expect(r2.chunks.find((c) => c.id === 'src/runner.ts')!.aliases).toEqual(['src/small.ts']);
    expect((await questions.list('src/runner.ts')).map((q) => q.chunkId)).toEqual(['src/runner.ts']);
    expect(await questions.list('src/small.ts')).toEqual([]);
    expect(await questions.list(beta.id)).toEqual([]);
    const prog = await new FsProgressStore('test-repo', env()).load();
    expect(Object.keys(prog.chunks)).toEqual(['src/runner.ts']);
  });

  it('reconciles progress the user saw at an older hash (e.g. after a pull)', async () => {
    const r1 = await scan();
    const alpha = r1.chunks.find((c) => c.id === 'src/big.ts#alpha')!;
    // Teammate scanned twice; this user only ever saw the first version.
    await put('src/big.ts', `${fn('alpha', 120, 0)}\n${fn('beta', 100)}\n`);
    await scan({ stores: { progress: new FsProgressStore('other-user', env()) } });
    await new FsProgressStore('test-repo', env()).save({ version: 1, repoId: 'test-repo', chunks: { [alpha.id]: passed(alpha.contentHash) } });
    await put('src/big.ts', `${fn('alpha', 120, 1)}\n${fn('beta', 100)}\n`);
    const r3 = await scan();
    expect(r3.reconciled.map((c) => c.id)).toEqual([alpha.id]);
    expect(r3.decayed).toEqual([]);
    expect(r3.reconciled[0]!.changeRatio).toBeCloseTo(1 / 123, 6);
  });

  it('dryRun writes nothing', async () => {
    const r = await scan({ dryRun: true });
    expect(r.chunks.length).toBeGreaterThan(0);
    await expect(readFile(repoPaths(root).chunks, 'utf8')).rejects.toThrow();
  });
});
