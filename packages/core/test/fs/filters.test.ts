import { describe, expect, it } from 'vitest';
import { resolveConfig } from '../../src/config/load.js';
import { ALWAYS_EXCLUDE, DEFAULT_EXCLUDE, DEFAULT_TEST_PATTERNS } from '../../src/config/defaults.js';
import { classifyContent, classifyPath, createMatcher, createPathFilters } from '../../src/fs/filters.js';

describe('createMatcher', () => {
  it('**/* matches everything', () => {
    const m = createMatcher(['**/*']);
    for (const p of ['a', 'a.ts', 'src/a.ts', 'a/b/c/d.py', '.gitignore', '.hidden/x']) expect(m(p)).toBe(true);
  });

  it('empty pattern list never matches', () => {
    expect(createMatcher([])('a.ts')).toBe(false);
    expect(createMatcher(['', '  '])('a.ts')).toBe(false);
  });

  it('**/dir/** matches at any depth including the root', () => {
    const m = createMatcher(['**/tests/**']);
    expect(m('tests/x.py')).toBe(true);
    expect(m('a/tests/x.py')).toBe(true);
    expect(m('a/b/tests/c/x.py')).toBe(true);
    expect(m('a/tests.py')).toBe(false);
    expect(m('a/mytests/x.py')).toBe(false);
  });

  it('handles the default exclude globs', () => {
    const m = createMatcher(DEFAULT_EXCLUDE);
    expect(m('node_modules/x/index.js')).toBe(true);
    expect(m('packages/a/node_modules/x.js')).toBe(true);
    expect(m('src/app.min.js')).toBe(true);
    expect(m('src/style.min.css')).toBe(true);
    expect(m('types/index.d.ts')).toBe(true);
    expect(m('types/index.d.mts')).toBe(true);
    expect(m('types/index.d.cts')).toBe(true);
    expect(m('sub/package-lock.json')).toBe(true);
    expect(m('poetry.lock')).toBe(true);
    expect(m('src/minimal.js')).toBe(false);
    expect(m('src/index.ts')).toBe(false);
    expect(m('src/distance.ts')).toBe(false);
  });

  it('handles the default test globs', () => {
    const m = createMatcher(DEFAULT_TEST_PATTERNS);
    for (const p of ['a.test.ts', 'src/a.spec.js', 'src/__tests__/b.ts', 'tests/test_x.py', 'pkg/test_y.py', 'pkg/y_test.py', 'tests/conftest.py', 'packages/core/test/a.ts', 'conftest.py'])
      expect(m(p), p).toBe(true);
    for (const p of ['src/a.ts', 'src/testing.py', 'src/attest.py', 'src/contest_test.ts']) expect(m(p), p).toBe(false);
  });

  it('ALWAYS_EXCLUDE matches dirs and lockfiles at any depth', () => {
    const m = createMatcher(ALWAYS_EXCLUDE);
    expect(m('node_modules/')).toBe(true);
    expect(m('a/node_modules/')).toBe(true);
    expect(m('a/node_modules/b/c.js')).toBe(true);
    expect(m('.git/')).toBe(true);
    expect(m('.gotchea/config.json')).toBe(true);
    expect(m('x/yarn.lock')).toBe(true);
    expect(m('x/app.min.js')).toBe(true);
    expect(m('src/builder.ts')).toBe(false);
    expect(m('src/vendors.ts')).toBe(false);
  });

  it('is case-sensitive and tolerates a leading ./', () => {
    const m = createMatcher(['**/*.ts']);
    expect(m('./src/a.ts')).toBe(true);
    expect(m('src/A.TS')).toBe(false);
  });

  it('honors negation', () => {
    const m = createMatcher(['**/*.ts', '!keep.ts']);
    expect(m('a.ts')).toBe(true);
    expect(m('keep.ts')).toBe(false);
  });
});

describe('classifyPath', () => {
  const config = resolveConfig({ include: ['src/**', 'tests/**', 'yarn.lock'], ignore: ['src/legacy/**'] });
  const filters = createPathFilters(config);

  it('applies always → include → exclude/ignore → test → accept in order', () => {
    expect(classifyPath('yarn.lock', filters, config)).toBe('always');
    expect(classifyPath('docs/a.ts', filters, config)).toBe('not-included');
    expect(classifyPath('src/a.d.ts', filters, config)).toBe('excluded');
    expect(classifyPath('src/legacy/a.ts', filters, config)).toBe('excluded');
    expect(classifyPath('tests/test_a.py', filters, config)).toBe('test');
    expect(classifyPath('src/a.rb', filters, config, (p) => p.endsWith('.ts'))).toBe('unsupported');
    expect(classifyPath('src/a.ts', filters, config, (p) => p.endsWith('.ts'))).toBeNull();
  });

  it('includeTests lets test files through', () => {
    const c = resolveConfig({ includeTests: true });
    expect(classifyPath('tests/test_a.py', createPathFilters(c), c)).toBeNull();
  });
});

describe('classifyContent', () => {
  const enc = (s: string) => new TextEncoder().encode(s);
  it('detects NUL bytes as binary', () => {
    expect(classifyContent(new Uint8Array([65, 0, 66]), [])).toBe('binary');
  });
  it('detects markers in the first 5 lines only', () => {
    expect(classifyContent(enc('// @generated by x\nconst a = 1;\n'), ['@generated'])).toBe('generated');
    expect(classifyContent(enc('1\n2\n3\n4\n# DO NOT EDIT\n'), ['DO NOT EDIT'])).toBe('generated');
    expect(classifyContent(enc('1\n2\n3\n4\n5\n// @generated\n'), ['@generated'])).toBeNull();
    expect(classifyContent(enc('plain\n'), ['@generated'])).toBeNull();
  });
});
